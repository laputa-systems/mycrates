#[path = "support/fixture.rs"]
mod fixture;

use fixture::TestServer;
use mycrates::acquire::fetch;
use mycrates::config::{Config, UpstreamConfig};
use mycrates::lockfile::{classify, parse_lockfile, PkgKind};
use mycrates::pins::{write_pins, PinEntry, Pins};
use mycrates::store::Store;
use mycrates::validate::validate_archive;
use tempfile::tempdir;

#[test]
#[ignore]
fn public_smoke_crates_io() {
    let dir = tempdir().unwrap();
    let state_dir = dir.path().join("state");
    let site_dir = dir.path().join("site");

    let lock_content = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "validation-probe"
version = "0.1.0"
dependencies = [
 "itoa",
]

[[package]]
name = "itoa"
version = "1.0.14"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "d75a2a4b1b190afb6f5425f10f6a8f959d2ea0b9c2b1d79553551850539e4674"
"#;

    let parsed = parse_lockfile(lock_content).unwrap();
    let mut registry_pins = Vec::new();
    let mut unsupported = Vec::new();
    for pkg in &parsed.package {
        let classified = classify(pkg);
        match classified.kind {
            PkgKind::CratesIo => {
                registry_pins.push(PinEntry {
                    name: pkg.name.clone(),
                    version: pkg.version.clone(),
                    checksum: pkg.checksum.clone().unwrap_or_default(),
                    source: pkg.source.clone().unwrap_or_default(),
                });
            }
            PkgKind::AlternateRegistry { url } => {
                unsupported.push(format!("{} (alternate registry: {})", pkg.name, url));
            }
            PkgKind::Git => {
                unsupported.push(format!("{} (git)", pkg.name));
            }
            PkgKind::Path | PkgKind::Workspace => {}
            PkgKind::Unsupported => {
                unsupported.push(format!("{} (unsupported)", pkg.name));
            }
        }
    }

    let pins = Pins {
        project: Some("public-smoke".to_string()),
        lock_path: Some(dir.path().join("Cargo.lock").display().to_string()),
        lock_content: Some(lock_content.to_string()),
        registry: registry_pins,
        unsupported,
    };
    let store = Store::new(state_dir.clone());
    let pins_path = store.pins_dir().join("public-smoke.toml");
    write_pins(&pins_path, &pins).unwrap();

    let cfg = Config {
        upstream: UpstreamConfig {
            index_url: "https://index.crates.io/".to_string(),
        },
        ..Default::default()
    };

    let summary = fetch(&state_dir, &cfg).unwrap();
    assert_eq!(summary.fetched_count, 1);

    let server = TestServer::start(state_dir.clone(), site_dir.clone(), "", None, false);
    let _ = server.mirror_index_url();
    let val_res = validate_archive(&state_dir, &pins_path).unwrap();
    assert_eq!(val_res.registry_count, 1);
    assert!(!val_res.is_partial);
}
