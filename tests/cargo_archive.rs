fn make_test_crate(name: &str, ver: &str) -> (Vec<u8>, String) {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
    let mut tar = Builder::new(&mut encoder);
    let cargo_toml = format!(
        "[package]\nname = \"{}\"\nversion = \"{}\"\nedition = \"2021\"\n",
        name, ver
    );
    let mut header = tar::Header::new_gnu();
    let path = format!("{}-{}/Cargo.toml", name, ver);
    header.set_path(&path).unwrap();
    header.set_size(cargo_toml.len() as u64);
    header.set_mode(0o644);
    header.set_cksum();
    tar.append(&header, cargo_toml.as_bytes()).unwrap();

    let code_path = format!("{}-{}/src/lib.rs", name, ver);
    let mut code_header = tar::Header::new_gnu();
    code_header.set_path(&code_path).unwrap();
    code_header.set_size(0);
    code_header.set_mode(0o644);
    code_header.set_cksum();
    tar.append(&code_header, &[][..]).unwrap();

    let _ = tar.into_inner().unwrap();
    let data = encoder.finish().unwrap();

    let mut h = Sha256::new();
    h.update(&data);
    let sha = format!("{:x}", h.finalize_reset());
    (data, sha)
}

#[test]
fn archive_via_replacement_unchanged_lock() {
    let dir = tempdir().unwrap();
    let state_dir = dir.path().join("state");
    let site_dir = dir.path().join("site");

    let server = TestServer::start(
        state_dir.clone(),
        site_dir.clone(),
        "",
        None,
        false,
    );

    // 1. Seed store and mirror with upstream crate `archived-dep` 0.1.0
    let (crate_bytes, cksum) = make_test_crate("archived-dep", "0.1.0");
    let store = Store::new(state_dir.clone());
    let sha = store.ingest_blob(&crate_bytes[..]).unwrap();
    assert_eq!(sha, cksum);

    let index_line = serde_json::json!({
        "name": "archived-dep",
        "vers": "0.1.0",
        "deps": [],
        "cksum": cksum.clone(),
        "features": {},
        "yanked": false
    })
    .to_string();

    let up_rec = UpstreamRecord {
        name: "archived-dep".to_string(),
        vers: "0.1.0".to_string(),
        checksum: cksum.clone(),
        raw_index_line: index_line,
        acquired_at: 1000,
    };
    store.put_upstream_record(&up_rec).unwrap();
    Publisher::new(&store, site_dir.clone(), server.base_url())
        .publish()
        .unwrap();

    // 2. Author a lockfile v3 with `archived-dep`
    let lock_content = format!(
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "archived-dep"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "{}"

[[package]]
name = "validation-probe"
version = "0.1.0"
dependencies = [
 "archived-dep",
]
"#,
        cksum
    );

    let pins = Pins {
        project: Some("sample-proj".to_string()),
        lock_path: Some("Cargo.lock".to_string()),
        lock_content: Some(lock_content.clone()),
        registry: vec![PinEntry {
            name: "archived-dep".to_string(),
            version: "0.1.0".to_string(),
            checksum: cksum,
            source: "registry+https://github.com/rust-lang/crates.io-index".to_string(),
        }],
        unsupported: vec![],
    };

    let pins_path = store.pins_dir().join("sample-proj.toml");
    write_pins(&pins_path, &pins).unwrap();

    // 3. Run validation probe
    let res = validate_project(&state_dir, &pins_path, &server.mirror_index_url()).unwrap();
    assert_eq!(res.project, "sample-proj");
    assert_eq!(res.registry_count, 1);
    assert!(!res.is_partial);
}

#[test]
fn real_workspace_with_dupes_and_targets_rejected_clearly() {
    let dir = tempdir().unwrap();
    let state_dir = dir.path().join("state");
    let store = Store::new(state_dir.clone());
    store.ensure_dirs().unwrap();

    let lock_content = r#"version = 3

[[package]]
name = "dup-dep"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"

[[package]]
name = "dup-dep"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"

[[package]]
name = "workspace-root"
version = "0.1.0"
dependencies = [
 "dup-dep 1.0.0",
 "dup-dep 2.0.0",
]
"#;

    let pins = Pins {
        project: Some("real-workspace".to_string()),
        lock_path: Some("Cargo.lock".to_string()),
        lock_content: Some(lock_content.to_string()),
        registry: vec![
            PinEntry {
                name: "dup-dep".to_string(),
                version: "1.0.0".to_string(),
                checksum: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa".to_string(),
                source: "registry+https://github.com/rust-lang/crates.io-index".to_string(),
            },
            PinEntry {
                name: "dup-dep".to_string(),
                version: "2.0.0".to_string(),
                checksum: "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb".to_string(),
                source: "registry+https://github.com/rust-lang/crates.io-index".to_string(),
            },
        ],
        unsupported: vec![],
    };
    let pins_path = store.pins_dir().join("real-workspace.toml");

    let mut pins_for_validate = pins.clone();
    for (i, pin) in pins.registry.iter().enumerate() {
        let blob_bytes = format!("fake-blob-{}-{}", pin.name, pin.version);
        let mut h = Sha256::new();
        h.update(&blob_bytes);
        pins_for_validate.registry[i].checksum = format!("{:x}", h.finalize_reset());
    }
    for pin in &pins_for_validate.registry {
        let blob_bytes = format!("fake-blob-{}-{}", pin.name, pin.version);
        std::fs::write(store.blobs_dir().join(format!("{}.crate", pin.checksum)), &blob_bytes).unwrap();
        let rec = UpstreamRecord {
            name: pin.name.clone(),
            vers: pin.version.clone(),
            checksum: pin.checksum.clone(),
            raw_index_line: serde_json::json!({
                "name": pin.name,
                "vers": pin.version,
                "deps": [],
                "cksum": pin.checksum,
                "features": {},
                "yanked": false
            })
            .to_string(),
            acquired_at: 1000,
        };
        store.put_upstream_record(&rec).unwrap();
    }
    let lock_content = lock_content
        .replace(
            "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
            &pins_for_validate.registry[0].checksum,
        )
        .replace(
            "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb",
            &pins_for_validate.registry[1].checksum,
        );
    pins_for_validate.lock_content = Some(lock_content);
    write_pins(&pins_path, &pins_for_validate).unwrap();
    let err = validate_project(&state_dir, &pins_path, "http://127.0.0.1:9999/mirror/").unwrap_err();
    let msg = format!("{err}");
    assert!(
        msg.contains("duplicate versions") || msg.contains("project directory"),
        "unexpected error: {msg}"
    );
}

